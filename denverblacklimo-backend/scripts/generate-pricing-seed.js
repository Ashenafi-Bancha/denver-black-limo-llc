/**
 * Regenerates migrations/009_seed_pricing.sql from pricing/dev-rates.json.
 *
 *   node scripts/generate-pricing-seed.js
 *
 * One source of truth: the JSON file is what the dev harness prices with, and
 * this script turns the same numbers into the production seed. Editing the SQL
 * by hand invites the two to disagree, so don't — edit the JSON and rerun.
 *
 * The seed uses ON CONFLICT DO NOTHING: it fills the rate card the first time
 * a deploy boots and never overwrites anything an admin has since edited in
 * the dashboard. Re-running migrations is therefore always safe.
 */
const fs = require('fs');
const path = require('path');

const rates = JSON.parse(
  fs.readFileSync(path.join(__dirname, '..', 'pricing', 'dev-rates.json'), 'utf8')
);

// SQL string literal: double any single quote inside the JSON.
const sqlString = (value) => `'${JSON.stringify(value).replace(/'/g, "''")}'`;

const rows = ['pricing_rates', 'pricing_vehicles', 'pricing_zones']
  .map((key) => `INSERT INTO site_settings (key, value)
VALUES ('${key}', ${sqlString(rates[key])}::jsonb)
ON CONFLICT (key) DO NOTHING;`)
  .join('\n\n');

const sql = `-- Price estimator rate card, seeded once.
-- GENERATED by scripts/generate-pricing-seed.js from pricing/dev-rates.json.
-- Do not edit by hand: edit the JSON and rerun the generator.
--
-- ON CONFLICT DO NOTHING means this fills an empty rate card on first boot
-- and never overwrites values an admin has edited in the dashboard since.

${rows}
`;

const out = path.join(__dirname, '..', 'migrations', '009_seed_pricing.sql');
fs.writeFileSync(out, sql);
console.log(`wrote ${out} (${sql.length} bytes)`);
